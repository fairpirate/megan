def generate_file(filename: str, content: str, file_format: str = "md") -> dict:
    ext = file_format.lstrip(".")
    filename = filename.replace("/", "_").replace("\\", "_")
    if not filename.endswith(f".{ext}"):
        filename = f"{filename}.{ext}"

    ts = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    stem = Path(filename).stem
    final_name = f"{stem}_{ts}.{ext}"
    path = OUTPUTS_DIR / final_name

    if ext == "pdf":
        return _save_pdf(path, content)
    elif ext == "docx":
        return _save_docx(path, content)
    else:
        path.write_text(content, encoding="utf-8")
        return {"status": "ok", "path": str(path), "filename": final_name}


def _save_pdf(path: Path, content: str) -> dict:
    try:
        from fpdf import FPDF
        pdf = FPDF()
        pdf.add_page()
        pdf.set_font("Helvetica", size=11)
        for line in content.split("\n"):
            line = line.encode("latin-1", errors="replace").decode("latin-1")
            pdf.multi_cell(0, 7, txt=line)
        pdf.output(str(path))
        return {"status": "ok", "path": str(path), "filename": path.name}
    except ImportError:
        txt = path.with_suffix(".txt")
        txt.write_text(content, encoding="utf-8")
        return {"status": "ok", "path": str(txt), "filename": txt.name,
                "note": "fpdf2 not installed — saved as .txt"}


def _save_docx(path: Path, content: str) -> dict:
    try:
        from docx import Document
        doc = Document()
        for line in content.split("\n"):
            if line.startswith("# "):   doc.add_heading(line[2:], level=1)
            elif line.startswith("## "): doc.add_heading(line[3:], level=2)
            elif line.startswith("### "):doc.add_heading(line[4:], level=3)
            elif line.strip():           doc.add_paragraph(line)
        doc.save(str(path))
        return {"status": "ok", "path": str(path), "filename": path.name}
    except ImportError:
        txt = path.with_suffix(".txt")
        txt.write_text(content, encoding="utf-8")
        return {"status": "ok", "path": str(txt), "filename": txt.name,
                "note": "python-docx not installed — saved as .txt"}


