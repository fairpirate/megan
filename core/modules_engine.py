def build_module(module_name: str, description: str, code: str) -> dict:
    MODULES_DIR.mkdir(parents=True, exist_ok=True)
    path = MODULES_DIR / f"{module_name}.py"
    header = textwrap.dedent(f"""\
        \"\"\"
        MEGAN Auto-Generated Module: {module_name}
        Description: {description}
        Created: {datetime.datetime.now().isoformat()}
        \"\"\"
        """)
    path.write_text(header + "\n" + code, encoding="utf-8")
    # Syntax check
    res = subprocess.run([sys.executable, "-m", "py_compile", str(path)],
                         capture_output=True, text=True)
    if res.returncode != 0:
        return {"status": "syntax_error", "error": res.stderr, "path": str(path)}
    return {"status": "ok", "path": str(path), "module": module_name}


def list_modules() -> list:
    if not MODULES_DIR.exists():
        return []
    return [p.stem for p in sorted(MODULES_DIR.glob("*.py")) if not p.stem.startswith("_")]


def list_outputs() -> list:
    if not OUTPUTS_DIR.exists():
        return []
    files = sorted(OUTPUTS_DIR.iterdir(), key=lambda p: p.stat().st_mtime, reverse=True)
    return [{"name": p.name, "size": p.stat().st_size, "path": str(p)} for p in files[:30]]


